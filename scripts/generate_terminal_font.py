#!/usr/bin/env python3
"""Generate the bounded 8x14 Cascadia Code Nerd Font bitmap terminal atlas; no device font install."""
import argparse
import hashlib
import subprocess
from pathlib import Path
from PIL import Image,ImageDraw,ImageFont

RANGES=((0x20,0x24f),(0x370,0x52f),(0x2000,0x206f),(0x2190,0x22ff),(0x2500,0x26ff),(0x2800,0x28ff))

def generate(font_path):
 charset=subprocess.check_output(["fc-query","-f","%{charset}",str(font_path)],text=True)
 supported=set()
 for item in charset.split():
  bounds=item.split("-");start=int(bounds[0],16);end=int(bounds[-1],16)
  supported.update(range(start,end+1))
 font=ImageFont.truetype(str(font_path),13,layout_engine=ImageFont.Layout.BASIC)
 def bitmap(code):
  image=Image.new("L",(8,14));draw=ImageDraw.Draw(image)
  if 0x2800<=code<=0x28ff:
   for bit,(x,y) in enumerate(((1,1),(1,4),(1,7),(5,1),(5,4),(5,7),(1,10),(5,10))):
    if (code-0x2800)&(1<<bit):draw.rectangle((x,y,x+1,y+1),fill=255)
  else:draw.text((0,-2),chr(code),font=font,fill=255)
  return [sum((1<<(7-x)) for x in range(8) if image.getpixel((x,y))>=100) for y in range(14)]
 glyphs=[]
 requested={c for start,end in RANGES for c in range(start,end+1)}
 requested.update(c for c in supported if 0xe000<=c<=0xf8ff or 0xf0000<=c<=0xf2fff)
 for code in sorted(requested):
  if code not in supported and not 0x2800<=code<=0x28ff:continue
  wire=code-0xf0000+0xa000 if code>=0xf0000 else code
  glyphs.append((wire,bitmap(code)))
 glyphs.sort()
 assert any(code==0x25a1 for code,_ in glyphs)
 lines=["/* Generated by scripts/generate_terminal_font.py; Cascadia Code + Nerd Font licenses: CASCADIA_FONT_LICENSE.txt and NERD_FONT_NOTICE.md. */",
        "/* Source font SHA256: "+hashlib.sha256(font_path.read_bytes()).hexdigest()+" */",
        "static const unsigned short mero_terminal_codes[]={"+",".join(hex(code) for code,_ in glyphs)+"};",
        "static const unsigned char mero_terminal_glyphs[][14]={"]
 lines += ["    {"+",".join(hex(v) for v in pixels)+"}," for _,pixels in glyphs]
 lines += ["};", "static const unsigned char *MeroTerminalGlyph(unsigned int code){",
           "    unsigned int lo=0,hi=sizeof(mero_terminal_codes)/sizeof(mero_terminal_codes[0]);",
           "    while(lo<hi){unsigned int mid=(lo+hi)/2;if(mero_terminal_codes[mid]<code)lo=mid+1;else hi=mid;}",
           "    if(lo<sizeof(mero_terminal_codes)/sizeof(mero_terminal_codes[0])&&mero_terminal_codes[lo]==code)return mero_terminal_glyphs[lo];",
           "    return MeroTerminalGlyph(0x25a1);", "}"]
 return "\n".join(lines)+"\n"

if __name__=="__main__":
 parser=argparse.ArgumentParser(description=__doc__);parser.add_argument("--font",type=Path,default=Path.home()/".local/share/fonts/CaskaydiaCoveNerdFontMono-Regular.ttf");parser.add_argument("--output",type=Path,default=Path(__file__).resolve().parents[1]/"wince/terminal/mero-terminal-font.h")
 args=parser.parse_args();args.output.write_text(generate(args.font))
